def 체결량30하락(d, how):
    """ v58: 체결량 30초 이평 하락 추세 여부 (1 = 하락, nan = 판정 불가 → 제외하지 않음) """
    if how == '10초':
        v = d['량30변화10']; return np.where(np.isnan(v), np.nan, v < 0)
    if how == '30초':
        v = d['량30변화30']; return np.where(np.isnan(v), np.nan, v < 0)

def 전일분봉급등(s_일자):
    """ v59: 직전 거래일 분봉 → {종목코드: 1분 최대 상승률 %} (분봉 종가 ÷ 직전 분 종가 − 1, 첫 봉은 시가 대비). 캐시 _초캐시/전일분봉_YYYYMMDD.pkl """
    path = os.path.join(folder_관성(), '_초캐시', f'전일분봉_{s_일자}.pkl')
    if os.path.exists(path):
        return pd.read_pickle(path)
    import sqlite3
    folder = os.path.join(ut.폴더manager.FolderManager().dic_폴더정보['데이터|차트수집'], '분봉')
    codes = set(np.load(os.path.join(folder_관성(), '_초캐시', f'초2_{s_일자}.npz'))['codes'].tolist())
    tabs = []
    for fn in sorted(os.listdir(folder)):
        if fn.endswith('.db') and fn[-10:-3].replace('_', '') <= s_일자[:6]:
            con = sqlite3.connect(os.path.join(folder, fn))
            tabs += [(r[0][-8:], fn) for r in con.execute("select name from sqlite_master where type='table'") if r[0][-8:] < s_일자]
            con.close()
    dic = {}
    if tabs:
        s_전일, fn = max(tabs)
        con = sqlite3.connect(os.path.join(folder, fn))
        df = pd.read_sql(f"select 종목코드, 시간, 시가, 종가 from ohlcv_분봉_{s_전일}", con); con.close()
        df = df[df['종목코드'].isin(codes)].sort_values(['종목코드', '시간'])
        prev = df.groupby('종목코드')['종가'].shift().fillna(df['시가'])
        df['r'] = (df['종가'] / prev.where(prev > 0) - 1) * 100
        dic = df.groupby('종목코드')['r'].max().to_dict()
    pd.to_pickle(dic, path)
    return dic



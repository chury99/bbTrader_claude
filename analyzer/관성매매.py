def _rsum(x, n):
    c = np.concatenate([[0.0], np.cumsum(x, dtype=np.float64)])
    out = np.full(len(x), np.nan); out[n - 1:] = c[n:] - c[:-n]
    return out


def _lag(x, n):
    if n == 0:
        return x
    out = np.full(len(x), np.nan); out[n:] = x[:-n]
    return out



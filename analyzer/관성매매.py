DIC_필터축 = {'이력': ('이력', '일'), '분폭': ('분폭', '')}     # v77 ⑬ 이력 N일 · v79 ⑭ 직전 5분 고저폭 N% - id 조각 '|이력N일|' · '|분폭N|'


def 필터요약(s_IS, s_OOS, s_축='이력'):
    """ v77 ⑬ 분봉 필터 (이력 N일) · v79 ⑭ 직전 5분 고저폭 (N%) - N 별 칸 평균과 조건 없음(같은 나머지 축) 대비 짝 비교 """
    a_, b_ = DIC_필터축[s_축]
    rows = []
    for k_, s_ in (('IS', s_IS), ('OOS', s_OOS)):
        x = s_[s_.index.str.contains(rf'\|{a_}\d+{b_}\|') & ~s_.index.str.startswith(('교차|', '급등|'))].copy()   # v70 진입 칸만
        if not len(x):
            return None
        x['N'] = x.index.str.extract(rf'\|{a_}(\d+){b_}\|')[0].astype(int).values
        x['기본'] = x.index.str.replace(rf'\|{a_}\d+{b_}', '', regex=True)
        x['구분'] = k_
        rows.append(x)
    x = pd.concat(rows)
    out = []
    for N, g in x.groupby('N'):
        r = dict(N=N)
        for k_ in ('IS', 'OOS'):
            z = g[g.구분 == k_].set_index('기본'); b = x[(x.N == 0) & (x.구분 == k_)].set_index('기본')
            r[f'건수_{k_}'] = z.건수.mean(); r[f'거래당_{k_}'] = z.거래당.mean(); r[f'나은_{k_}'] = (z.거래당 > b.거래당.reindex(z.index)).sum() if N else np.nan
            r[f'칸_{k_}'] = len(z)
            zt = z[(z.건수 >= N_선정최소건수) & z.t.notna()].t if k_ == 'IS' else z.t.dropna()      # IS 최고 칸은 선정과 같은 최소 건수 이상에서
            r[f'최고t_{k_}'] = zt.idxmax() if len(zt) else None
        zi, zo = g[g.구분 == 'IS'].set_index('기본'), g[g.구분 == 'OOS'].set_index('기본')
        bi, bo = x[(x.N == 0) & (x.구분 == 'IS')].set_index('기본'), x[(x.N == 0) & (x.구분 == 'OOS')].set_index('기본')
        r['둘다'] = ((zi.거래당 > bi.거래당.reindex(zi.index)) & (zo.거래당.reindex(zi.index) > bo.거래당.reindex(zi.index))).sum() if N else np.nan
        out.append(r)
    f = pd.DataFrame(out)
    return f.set_index('N') if f['N'].nunique() > 1 else None          # 축 값이 하나뿐이면 (v78) 절을 만들지 않는다



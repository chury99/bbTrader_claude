def 호가단위(x):
    return 1 if x < 2000 else 5 if x < 5000 else 10 if x < 20000 else 50 if x < 50000 else 100 if x < 200000 \
        else 500 if x < 500000 else 1000


def 호가올림(x):
    u = 호가단위(x)
    return np.ceil(x / u - 1e-9) * u


def 청산(d, t, c):
    """ t초 신호 → (청산초, 매수가, 청산가, 순수익%, 사유) """
    p, hi, lo = d['p'], d['hi'], d['lo']
    E = max(p[t] * (1 + 매수슬립 / 100), p[t] + 2 * 호가단위(p[t]))
    SL = E * (1 - c['손절'] / 100) if c.get('손절') else -np.inf
    TP = 호가올림(E * (1 + c['익절'] / 100)) if c.get('익절') else None
    tr = c.get('트레일'); fade = c.get('소멸')
    vk = c.get('확인'); b_확인 = bool(vk)   # v75: (N초, '강도'|'가격'|'량') - 진입 N초 뒤 첫 거래 초에 확인 못 하면 청산
    vf = c.get('대금꺼짐')  # v72: dict(방식 '한번'|'지속', N초, 비율, 기준 '진입5'|'진입30'|'현재30', 연속) - 거래대금 5초 이평 < 기준 × 비율이면 청산 (최소보유 무관)
    b_꺼짐 = bool(vf); k_꺼짐 = 0                       #   한번 = N초 뒤 첫 거래 초에만 · 지속 = N초 뒤부터 매 초, 연속 초 이어지면 (v71 은 기준 '진입5')
    f0 = (d['대금5'][t] if vf['기준'] == '진입5' else d['대금30'][t]) if vf else np.nan
    vt = c.get('검증')      # v51: (N초, 기준%, '가격'|'고점') - 진입 N초 뒤 첫 판정 초에 종가(가격) 또는 그때까지 고가(고점)가 매수가 × (1+기준%) 미만이면 청산
    b_검증 = bool(vt)
    n_연속, n_최소 = c.get('돌파연속', 1), c.get('최소보유', 0)   # v51: 하향돌파가 n_연속 초 이어져야 · 진입 후 n_최소 초 전에는 하향돌파로 나가지 않음
    k_아래, k_가격, k_둘 = 0, 0, 0
    n_가격 = c.get('가격연속', 1)                     # v64: 종가가 가격 30초 이평 아래에 n_가격 초 이어지면 청산 (최소보유 적용)
    p30 = d['가격30']
    peak = E
    s_끝 = min(t + c['보유'], S_마감, len(p) - 1)
    for s in range(t + 1, s_끝 + 1):
        if not d['유효'][s]:                               # 거래 시간이 아닌 초(정지 중)에는 판정할 값이 없다
            continue
        stop =max(SL, peak * (1 - tr / 100)) if tr else SL
        b_stop = lo[s] == lo[s] and lo[s] <= stop + 1e-9
        b_tp = TP is not None and hi[s] == hi[s] and hi[s] > TP + 1e-9
        if b_stop:
            X = min(stop, p[s]) * (1 - 매도슬립 / 100)
            return s, E, X, (X / E - 1) * 100 - 비용, '손절' if stop <= SL + 1e-9 else '트레일'
        if b_tp:
            return s, E, TP, (TP / E - 1) * 100 - 비용, '익절'
        if b_검증 and s - t >= vt[0]:                      # 손절·익절 판정 뒤 (같은 초에 손절선이 닿았으면 손절이 먼저)
            b_검증 = False
            v = p[s] if vt[2] == '가격' else max(peak, hi[s] if hi[s] == hi[s] else -np.inf)
            if v < E * (1 + vt[1] / 100) - 1e-9:
                X = p[s] * (1 - 매도슬립 / 100)
                return s, E, X, (X / E - 1) * 100 - 비용, '검증'
        if b_확인 and s - t >= vk[0]:                      # v75 확인 (손절·트레일 판정 뒤)
            b_확인 = False
            if not ((d['체결강도10'][s] >= 100) if vk[1] == '강도' else (p[s] >= p[t]) if vk[1] == '가격' else (d['체결량30'][s] >= d['체결량30'][t])):
                X = p[s] * (1 - 매도슬립 / 100)
                return s, E, X, (X / E - 1) * 100 - 비용, '확인실패'
        if b_꺼짐 and s - t >= vf['N']:                     # v71·v72 거래대금 꺼짐
            if vf['방식'] == '한번':
                b_꺼짐 = False
            기준 = d['대금30'][s] if vf['기준'] == '현재30' else f0
            k_꺼짐 = k_꺼짐 + 1 if 기준 > 0 and d['대금5'][s] < 기준 * vf['비율'] else 0
            if k_꺼짐 >= vf.get('연속', 1):
                X = p[s] * (1 - 매도슬립 / 100)
                return s, E, X, (X / E - 1) * 100 - 비용, '대금꺼짐'
        if fade is not None and d['체결강도10'][s] == d['체결강도10'][s] and d['체결강도10'][s] < fade:
            X = p[s] * (1 - 매도슬립 / 100)
            return s, E, X, (X / E - 1) * 100 - 비용, '소멸'
        if c.get('빠른돌파') and d['속도3v'][s] == d['속도3v'][s] and d['속도3v'][s] < d['속도30'][s]:   # v51: 3초 이평이 30초 이평 아래로
            X = p[s] * (1 - 매도슬립 / 100)
            return s, E, X, (X / E - 1) * 100 - 비용, '빠른돌파'
        k_아래 = k_아래 + 1 if (d['량5위30'] if c.get('돌파기준') == '체결량' else d['5초위30초'])[s] == 0 else 0   # v55: 하향돌파 기준 건수 / 체결량
        if c.get('하향돌파') and k_아래 >= n_연속 and s - t >= n_최소:
            X = p[s] * (1 - 매도슬립 / 100)
            return s, E, X, (X / E - 1) * 100 - 비용, '하향돌파'
        k_가격 = k_가격 + 1 if p[s] < p30[s] else 0      # 이평이 없으면(nan) 비교가 거짓 → 0
        if c.get('가격돌파') and k_가격 >= n_가격 and s - t >= n_최소:
            X = p[s] * (1 - 매도슬립 / 100)
            return s, E, X, (X / E - 1) * 100 - 비용, '가격이탈'
        k_둘 = k_둘 + 1 if (p[s] < p30[s] and d['5초위30초'][s] == 0) else 0   # v65: 가격·건수 둘 다 아래
        if c.get('둘다') and k_둘 >= c.get('둘다연속', 1) and s - t >= n_최소:
            X = p[s] * (1 - 매도슬립 / 100)
            return s, E, X, (X / E - 1) * 100 - 비용, '둘다이탈'
        if hi[s] == hi[s]:
            peak = max(peak, hi[s])
    X = p[s_끝] * (1 - 매도슬립 / 100)
    return s_끝, E, X, (X / E - 1) * 100 - 비용, '마감' if s_끝 >= S_마감 else '시간'


def 거래생성(dic_지표, c):
    li = []
    for code, d in dic_지표.items():
        idx = np.flatnonzero(마스크(d, c))
        nxt, k = 0, 0
        while not c['일최대'] or k < c['일최대']:   # 일최대 0 = 제한 없음 (v47, v46 까지 3회)
            j = np.searchsorted(idx, nxt)
            if j >= len(idx):
                break
            t = int(idx[j])
            s, E, X, r, why = 청산(d, t, c)
            li.append((code, t, s, E, X, r, why))
            k += 1; nxt = s + c['쿨다운']   # 같은 종목만 - 청산 초 + 쿨다운 부터 다음 신호 (v47 5초, v46 까지 60초)
    return li



def 일봉판():
    """ 일봉 db 전체 → 시가·고가·저가·종가·대금(원) 판 (행 일자 · 열 종목코드) - 한 번 읽으면 재사용 """
    global _판
    if _판 is not None:
        return _판
    li = []
    for f in sorted(os.listdir(folder_일봉())):
        if not (f.startswith('ohlcv_일봉_') and f.endswith('.db')):
            continue
        con = sqlite3.connect(os.path.join(folder_일봉(), f))
        for (t,) in con.execute("select name from sqlite_master where type='table'"):
            li.append(pd.read_sql(f"select 일자, 종목코드, 시가, 고가, 저가, 종가, \"거래대금(백만)\" as 대금 from '{t}'", con))
        con.close()
    df = pd.concat(li).drop_duplicates(['일자', '종목코드'], keep='last')
    판 = {k: df.pivot(index='일자', columns='종목코드', values=k).sort_index().astype(float) for k in ('시가', '고가', '저가', '종가', '대금')}
    판['대금'] = 판['대금'] * 1e6
    _판 = 판
    return 판


def 일봉특징(판):
    """ D 일 행에 D−1 일까지의 값 (shift 1) → {특징: 판} """
    c, h, a = 판['종가'], 판['고가'], 판['대금']
    with np.errstate(all='ignore'):
        f = dict(전일시가=판['시가'].shift(1), 전일고가=h.shift(1), 전일저가=판['저가'].shift(1), 전일종가=c.shift(1), 전전일종가=c.shift(2), 종가6=c.shift(6),
                 ma5=c.rolling(5).mean().shift(1), ma20=c.rolling(20).mean().shift(1), ma60=c.rolling(60).mean().shift(1),
                 대금20=a.rolling(20, min_periods=10).mean().shift(1), 고가60=h.rolling(60, min_periods=20).max().shift(1))
    return f



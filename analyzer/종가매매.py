def 표준화값(df, mu, sd, 특징=None):
    X = ((df[특징 or LI_특징].astype(float) - mu) / sd).clip(-5, 5)
    return np.nan_to_num(X.values)


def 로지스틱(X, y, lam=1.0, it=30):
    """ 뉴턴법 + L2 (절편 제외) → 가중치 [절편, 특징...] """
    Xb = np.c_[np.ones(len(X)), X]; w = np.zeros(Xb.shape[1]); R = np.eye(Xb.shape[1]); R[0, 0] = 0
    for _ in range(it):
        p = 1 / (1 + np.exp(-np.clip(Xb @ w, -30, 30)))
        g = Xb.T @ (p - y) + lam * R @ w
        Hs = (Xb * (p * (1 - p))[:, None]).T @ Xb + lam * R
        dw = np.linalg.solve(Hs, g); w -= dw
        if np.abs(dw).max() < 1e-7:
            break
    return w


def 학습(df_학습, 특징=None):
    특징 = list(특징 or LI_특징)
    mu, sd = df_학습[특징].astype(float).mean(), df_학습[특징].astype(float).std().replace(0, 1)
    w = 로지스틱(표준화값(df_학습, mu, sd, 특징), df_학습['정답'].values.astype(float))
    return dict(w=w, mu=mu, sd=sd, 특징=특징)


def 채점(df, 모델):
    df = df.copy()
    df['점수'] = 모델['w'][0] + 표준화값(df, 모델['mu'], 모델['sd'], 모델.get('특징')) @ 모델['w'][1:]
    df['확률'] = 1 / (1 + np.exp(-df['점수'])) * 100
    df['순위'] = df.groupby('일자')['점수'].rank(ascending=False, method='first')
    df['등락순위'] = df.groupby('일자')['등락'].rank(ascending=False, method='first')
    return df


def AUC(y, s):
    y = np.asarray(y); r = pd.Series(s).rank().values; n1 = y.sum(); n0 = len(y) - n1
    return (r[y == 1].sum() - n1 * (n1 + 1) / 2) / (n1 * n0) if n1 and n0 else np.nan



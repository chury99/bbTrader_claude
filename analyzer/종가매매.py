def 분봉배열(s_일자, s_파일, li_코드=None):
    """ 하루 분봉 → (종목코드, 시가·고가·저가·종가·거래량 n×391 배열 - 봉이 없는 분은 nan, 거래량 0) """
    con = sqlite3.connect(os.path.join(ut.분봉급등.folder_분봉(), s_파일))
    s_조건 = '' if li_코드 is None else " where 종목코드 in (" + ','.join(f"'{c}'" for c in li_코드) + ")"
    df = pd.read_sql(f"select 종목코드, 시간, 시가, 고가, 저가, 종가, 거래량 from 'ohlcv_분봉_{s_일자}'{s_조건}", con)
    con.close()
    df['m'] = df['시간'].str[:2].astype(int) * 60 + df['시간'].str[3:5].astype(int) - 540
    df = df[(df['m'] >= 0) & (df['m'] < N_분)]
    codes, ci = np.unique(df['종목코드'].values, return_inverse=True)
    n = len(codes)
    O = np.full((n, N_분), np.nan); H = O.copy(); L = O.copy(); C = O.copy(); V = np.zeros((n, N_분))
    mi = df['m'].values
    O[ci, mi] = df['시가'].values; H[ci, mi] = df['고가'].values; L[ci, mi] = df['저가'].values
    C[ci, mi] = df['종가'].values; V[ci, mi] = df['거래량'].values
    return codes, O, H, L, C, V


def _ffill(X):
    return pd.DataFrame(X.T).ffill().values.T


def _첫도달(mask):
    """ 행마다 처음 참인 열 (없으면 −1) """
    return np.where(mask.any(1), mask.argmax(1), -1)


def build_일캐시(args):
    """ D 일 15:15 시점 분봉 특징 + D+1 일 결과 → 일_D.pkl """
    s_일자, s_파일, s_다음, s_다음파일 = args
    path = os.path.join(folder_캐시(), f'일_{s_일자}.pkl')
    if os.path.exists(path):
        return s_일자, '있음'
    codes, O, H, L, C, V = 분봉배열(s_일자, s_파일)
    Cf = _ffill(C)
    with np.errstate(all='ignore'):
        e = np.where(np.isfinite(O[:, M_진입]), O[:, M_진입], Cf[:, M_진입 - 1])           # 진입가 = 15:15 봉 시가 (봉이 없으면 직전 종가)
        A = np.nan_to_num(V * Cf)                                                        # 분 거래대금 (원)
        r1 = np.c_[np.full(len(codes), np.nan), (Cf[:, 1:] / Cf[:, :-1] - 1) * 100]
        ok = np.zeros(Cf.shape, bool); ok[:, 1:M_진입] = True; ok &= (V > 0) & (Cf >= 1000)
        ev = ok & (r1 >= N_급등)
        ok_종 = np.zeros(Cf.shape, bool); ok_종[:, 1:380] = True; ok_종 &= (V > 0) & (Cf >= 1000)
        시가 = np.array([o[np.isfinite(o)][0] if np.isfinite(o).any() else np.nan for o in O])
        hh, ll = H[:, :M_진입], L[:, :M_진입]
        df = pd.DataFrame(dict(
            진입가=e, 시가=시가, 고가=np.nanmax(hh, 1), 저가=np.nanmin(ll, 1), 종가=Cf[:, -1],
            대금=A[:, :M_진입].sum(1), 대금후반=A[:, 345:M_진입].sum(1),                       # 14:45 ~ 15:14
            c1414=Cf[:, 314], c1444=Cf[:, 344], c1504=Cf[:, 364],
            vwap=A[:, :M_진입].sum(1) / np.where(V[:, :M_진입].sum(1) > 0, V[:, :M_진입].sum(1), np.nan),
            최대1분=np.nanmax(np.where(ok, r1, np.nan), 1), n4유=(ev & (A >= N_유동)).sum(1),
            n4유종일=(ok_종 & (r1 >= N_급등) & (A >= N_유동)).sum(1),
            고가분=np.where(np.isfinite(hh).any(1), np.nanargmax(np.where(np.isfinite(hh), hh, -np.inf), 1), -1)),
            index=pd.Index(codes, name='종목코드'))
    # D+1 결과
    c1, O1, H1, L1, C1, V1 = 분봉배열(s_다음, s_다음파일)
    k = pd.Index(c1).get_indexer(codes)
    m = k >= 0
    def 맞춤(X):
        out = np.full((len(codes),) + X.shape[1:], np.nan); out[m] = X[k[m]]
        return out
    O1, H1, L1, C1f = 맞춤(O1), 맞춤(H1), 맞춤(L1), 맞춤(_ffill(C1))
    with np.errstate(all='ignore'):
        h1, l1 = np.nan_to_num(H1[:, :M_진입], nan=-np.inf), np.nan_to_num(L1[:, :M_진입], nan=np.inf)
        df['다음시가'] = np.array([o[np.isfinite(o)][0] if np.isfinite(o).any() else np.nan for o in O1])
        df['다음청산'] = np.where(np.isfinite(O1[:, M_진입]), O1[:, M_진입], C1f[:, M_진입 - 1])   # D+1 15:15 봉 시가
        df['다음고가'] = np.nanmax(H1[:, :M_진입], 1); df['다음저가'] = np.nanmin(L1[:, :M_진입], 1); df['다음종가'] = C1f[:, -1]
        for u in LI_상승:
            df[f'상{u}'] = _첫도달(h1 >= (e * (1 + u / 100))[:, None])
        for s in LI_하락:
            df[f'하{s}'] = _첫도달(l1 <= (e * (1 - s / 100))[:, None])
    df['다음일자'] = s_다음
    os.makedirs(folder_캐시(), exist_ok=True)
    tmp = f'{path}.{os.getpid()}.tmp'
    df.to_pickle(tmp); os.replace(tmp, path)
    return s_일자, len(df)



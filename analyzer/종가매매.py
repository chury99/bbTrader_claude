def 캐시보충(n_proc=N_병렬):
    li = [x for x in li_분봉쌍() if not os.path.exists(os.path.join(folder_캐시(), f'일_{x[0]}.pkl'))]
    if li:
        print(f'날짜 캐시 보충 {len(li)}일 ({li[0][0]} ~ {li[-1][0]})', flush=True)
        with Pool(n_proc) as pool:
            for r in pool.imap_unordered(build_일캐시, li):
                print(r, flush=True)
    li2 = [x for x in li_분봉쌍() if not os.path.exists(os.path.join(folder_캐시(), f'종_{x[0]}.pkl'))]
    if li2:
        print(f'전일 종가 기준 캐시 보충 {len(li2)}일', flush=True)
        with Pool(n_proc) as pool:
            for r in pool.imap_unordered(build_종캐시, li2):
                print(r, flush=True)
    li3 = [x for x in li_분봉쌍() if not os.path.exists(os.path.join(folder_캐시(), f'봉_{x[0]}.pkl'))]
    if li3:
        print(f'판단봉 손절 캐시 보충 {len(li3)}일', flush=True)
        with Pool(n_proc) as pool:
            for r in pool.imap_unordered(build_봉캐시, li3):
                print(r, flush=True)
    return li



def 슬롯계좌(t, li_IS, li_OOS, n칸=N_기준K):
    """ 5칸 계좌 - 날짜 순으로 D 15:15 에 빈 칸만 그날 상위 종목 (이미 든 종목 제외) 으로 채운다. 한 칸 = 처음 자본의 1/5 (단리)
        청산일 = D 의 청산일차 번째 다음 거래일 (그날 15:15 전에 비면 그날 다시 채운다) """
    일 = [x[0] for x in ut.분봉급등.li_분봉일자()]; pos = {d: i for i, d in enumerate(일)}
    t = t.copy(); t['청산일'] = [일[min(pos[d] + int(k), len(일) - 1)] for d, k in zip(t['일자'], t['청산일차'])]
    t = t.sort_values(['일자', '순위'])
    보유, 체결, 동시 = [], [], {}
    for d in sorted(set(li_IS) | set(li_OOS)):
        보유 = [x for x in 보유 if x['청산일'] > d]
        for _, r in t[t['일자'] == d].iterrows():
            if len(보유) >= n칸:
                break
            if r['종목코드'] in {x['종목코드'] for x in 보유}:
                continue
            보유.append(r.to_dict()); 체결.append(r)
        동시[d] = len(보유)                                                  # 그날 15:15 에 산 뒤 들고 있는 종목 수
    c = pd.DataFrame(체결)
    c['구분'] = np.where(c['일자'].isin(li_IS), 'IS', 'OOS')
    eq = (c.groupby('청산일')['수익'].sum() / n칸).sort_index()
    무제한 = {d: ((t['일자'] <= d) & (t['청산일'] > d)).sum() for d in sorted(set(li_IS) | set(li_OOS))}
    out = dict(신호=len(t), 체결=len(c), 체결률=len(c) / len(t) * 100, 평균동시=np.mean(list(동시.values())),
               무제한평균=np.mean(list(무제한.values())), 무제한최대=max(무제한.values()),
               누적=eq.sum(), MDD=(eq.cumsum() - eq.cumsum().cummax()).min())
    for nm in ('IS', 'OOS'):
        x = c[c['구분'] == nm]; out[f'거래당{nm}'] = x['수익'].mean(); out[f'건수{nm}'] = len(x); out[f'누적{nm}'] = x['수익'].sum() / n칸
        out[f'하루{nm}'] = len(x) / len(li_IS if nm == 'IS' else li_OOS)
    out['곡선'] = eq; out['동시'] = pd.Series(동시); out['무제한'] = pd.Series(무제한); out['체결원장'] = c
    return out



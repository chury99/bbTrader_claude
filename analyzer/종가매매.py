def 자금운영(t, li_IS, li_OOS, n시작=N_시작자본):
    """ v17 자금운영 - D 15:15 에 그날 사는 종목 수 n 으로 자본을 1/n 씩 나눠 정수 주수로 사고, D+1 에 회수한 전부를 다음 진입에 다시 1/n (복리)
        구분 = 전체 (IS + OOS 날짜 순) · IS 날만 · OOS 날만 → dict(곡선={구분: Series(일자 → 회수 뒤 자본)}, 요약=[...]) """
    곡선, 요약 = {}, []
    for nm, li in (('전체', sorted(li_IS + li_OOS)), ('IS', sorted(li_IS)), ('OOS', sorted(li_OOS))):
        cap, li_cap, 못산, 놀림, n진입, 최고, mdd = float(n시작), [], 0, [], [], float(n시작), 0.0
        for d in li:
            g = t[t['일자'] == d]
            if len(g):
                배분 = cap / len(g)
                주 = np.floor(배분 / g['진입가'].values)
                투입 = 주 * g['진입가'].values
                cap0 = cap
                cap += float((투입 * g['수익'].values / 100).sum())
                못산 += int((주 == 0).sum()); 놀림.append((cap0 - 투입.sum()) / cap0 * 100); n진입.append(int((주 > 0).sum()))
            else:
                n진입.append(0)
            li_cap.append(cap); 최고 = max(최고, cap); mdd = min(mdd, (cap / 최고 - 1) * 100)
        곡선[nm] = pd.Series(li_cap, index=pd.to_datetime(li))
        요약.append(dict(구분=nm, 거래일=len(li), 하루=np.mean(n진입), 빈날=sum(x == 0 for x in n진입), 최종=cap, 수익률=(cap / n시작 - 1) * 100, MDD=mdd,
                       못산=못산, 놀림=float(np.mean(놀림)) if 놀림 else 0.0))
    return dict(곡선=곡선, 요약=요약)


